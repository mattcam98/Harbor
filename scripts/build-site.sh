#!/usr/bin/env bash
# Writes the download page's data for a Harbor Setup release:
#   site/release.json  version, size and digests, which the page shows
#   site/install.sh    what the page's Terminal line runs: downloads Harbor
#                      Setup, checks its SHA-256, and starts it
#
#   build-site.sh ZIP REPOSITORY PAGES_URL [TAG]
#
#   ZIP         HarborSetup-mac.zip, as attached to the release
#   REPOSITORY  owner/name of the GitHub repository that holds the release
#   PAGES_URL   where the page is served, e.g. https://owner.github.io/name
#   TAG         the release's tag (default: v<version inside the zip>)
#
# The Pages workflow runs this against the latest release of whatever
# repository it runs in, so a fork publishes its own page. Both files are
# generated and not committed. Needs bash and python3; runs on Linux and macOS.
set -euo pipefail
cd "$(dirname "$0")/.."

[ $# -ge 3 ] || { sed -n '2,17p' "$0" | sed 's/^# \{0,1\}//' >&2; exit 2; }
zip=$1 repo=$2 pages=${3%/} tag=${4:-}
[ -f "$zip" ] || { echo "No file at $zip" >&2; exit 1; }
[ "$(basename "$zip")" = HarborSetup-mac.zip ] || { echo "The download must be named HarborSetup-mac.zip" >&2; exit 1; }

mkdir -p site
# Written aside and moved into place, so a refused release leaves no
# half-written page data behind.
release=$(mktemp)
trap 'rm -f "$release"' EXIT
python3 -I - "$zip" "$repo" "$pages" "$tag" > "$release" <<'PY'
import datetime, hashlib, io, json, os, plistlib, re, sys, zipfile

zip_path, repo, pages, tag = sys.argv[1:5]
if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repo):
    sys.exit(f"Not an owner/name repository: {repo}")
# Both end up inside install.sh, which people pipe into bash.
if tag and not re.fullmatch(r"[A-Za-z0-9._-]+", tag):
    sys.exit(f"Release tags may only use letters, digits, dots, dashes and underscores: {tag}")
if not re.fullmatch(r"https://[A-Za-z0-9.-]+(/[A-Za-z0-9._~-]+)*", pages):
    sys.exit(f"Not a plain https address: {pages}")

with zipfile.ZipFile(zip_path) as outer:
    names = set(outer.namelist())
    for part in ("install-harbor", "harbor-setup", "harbor-setup-mac", "Harbor.ipa", "Harbor.ipa.sha256"):
        if f"Harbor Setup/{part}" not in names:
            sys.exit(f"{zip_path} has no Harbor Setup/{part}")
    ipa_sha256 = outer.read("Harbor Setup/Harbor.ipa.sha256").decode().split()[0]
    with zipfile.ZipFile(io.BytesIO(outer.read("Harbor Setup/Harbor.ipa"))) as ipa:
        plists = [n for n in ipa.namelist() if re.fullmatch(r"Payload/[^/]+\.app/Info\.plist", n)]
        if len(plists) != 1:
            sys.exit("Harbor.ipa does not hold exactly one app")
        info = plistlib.loads(ipa.read(plists[0]))

digest = hashlib.sha256()
with open(zip_path, "rb") as f:
    for block in iter(lambda: f.read(1 << 20), b""):
        digest.update(block)

version = info["CFBundleShortVersionString"]
if not re.fullmatch(r"[0-9A-Za-z.-]+", version):
    sys.exit(f"Unexpected version: {version}")
tag = tag or f"v{version}"
json.dump({
    "version": version,
    "buildVersion": info.get("CFBundleVersion", "1"),
    "date": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
    "minOSVersion": info.get("MinimumOSVersion", "17.0"),
    "repository": f"https://github.com/{repo}",
    "installCommand": f'/bin/bash -c "$(curl -fsSL {pages}/install.sh)"',
    "setup": {
        "url": f"https://github.com/{repo}/releases/download/{tag}/HarborSetup-mac.zip",
        "size": os.path.getsize(zip_path),
        "sha256": digest.hexdigest(),
    },
    "harborIPASha256": ipa_sha256,
}, sys.stdout, indent=2)
sys.stdout.write("\n")
PY
mv "$release" site/release.json

field() { python3 -I -c 'import functools, json, sys; print(functools.reduce(lambda d, k: d[k], sys.argv[1:], json.load(open("site/release.json"))))' "$@"; }
version=$(field version)
url=$(field setup url)
sha256=$(field setup sha256)

cat > site/install.sh <<EOF
#!/bin/bash
# Installs Harbor on an iPhone from this Mac, once:
#
#   $(field installCommand)
#
# Downloads Harbor Setup $version, checks it against the SHA-256 below and
# starts it. Harbor Setup asks for your Apple ID, signs Harbor with it and
# installs it on the iPhone connected by cable. Your password goes only to
# Apple. Generated by scripts/build-site.sh.
set -euo pipefail
# Plain ASCII and braced variables only: /bin/bash 3.2 in a UTF-8 locale
# reads a non-ASCII byte after a bare \$name as part of the name.

version="$version"
url="$url"
sha256="$sha256"

fail() { echo "\$*" >&2; exit 1; }
[ "\$(uname -s)" = Darwin ] || fail "Harbor Setup runs on a Mac."
[ "\$(uname -m)" = arm64 ] || fail "Harbor Setup needs a Mac with Apple silicon."
if [ "\$(sw_vers -productVersion | cut -d. -f1)" -lt 26 ]; then
  echo "Harbor Setup is made for macOS 26 or later. Trying anyway." >&2
fi

home="\${HOME}/Library/Application Support/Harbor Setup/\${version}"
if [ ! -x "\${home}/Harbor Setup/install-harbor" ]; then
  download=\$(mktemp -d)
  trap 'rm -rf "\${download}"' EXIT
  echo "Downloading Harbor Setup \${version}..."
  curl -fL --proto '=https' --tlsv1.2 --progress-bar -o "\${download}/setup.zip" "\${url}"
  [ "\$(shasum -a 256 "\${download}/setup.zip" | cut -d' ' -f1)" = "\${sha256}" ] \\
    || fail "The download doesn't match its published SHA-256, so nothing was run."
  rm -rf "\${home}"
  mkdir -p "\${home}"
  ditto -x -k "\${download}/setup.zip" "\${home}"
  # exec below skips the trap, so tidy up here.
  rm -rf "\${download}"
  trap - EXIT
fi

echo
echo "Connect your iPhone with a cable, unlock it, and tap Trust if asked."
echo
exec "\${home}/Harbor Setup/install-harbor" "\$@"
EOF
chmod 755 site/install.sh
if LC_ALL=C grep -n '[^[:print:][:space:]]' site/install.sh >&2; then
  echo "site/install.sh must be plain ASCII (see the note inside it)." >&2
  exit 1
fi

echo "Wrote site/release.json and site/install.sh for Harbor $version from $repo."
